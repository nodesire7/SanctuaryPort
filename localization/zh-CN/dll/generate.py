"""Generate the export forwarders of the SDL3 proxy DLL.

The proxy takes the place of ``bin\\SDL3.dll`` and must export every name the real library
exports, or the loader refuses to start the executables that import them. Each name becomes a
one-instruction stub that jumps to the address the proxy resolved from the real library at load
time (``SDL3.real.dll``, shipped beside it), so no calling convention or signature is needed
here.

usage: python generate.py EXPORTS.json OUT_DIR
  EXPORTS.json: a JSON array of names, as read from the real DLL's export table
"""
import json
import sys
from pathlib import Path

HEADER = "/* Generated by generate.py from the real SDL3 export table. Do not edit. */\n"
STUB = """
    .globl {name}
    .p2align 4
{name}:
    jmp *sdl3_targets+{offset}(%rip)
"""

C_SOURCE = """/* Generated by generate.py: the forward table and the library it resolves against. */
#include <windows.h>

#define COUNT {count}

typedef void (*target_t)(void);

target_t sdl3_targets[COUNT];

static HMODULE real_library;

static void missing_export(void) {{}}

static void load_real(HINSTANCE self) {{
    char path[MAX_PATH];
    DWORD len = GetModuleFileNameA((HMODULE)self, path, MAX_PATH);
    if (len == 0 || len >= MAX_PATH) return;
    char *slash = path + len;
    while (slash > path && *slash != '\\\\') slash--;
    if (*slash != '\\\\') return;
    lstrcpyA(slash + 1, "SDL3.real.dll");
    real_library = LoadLibraryA(path);
    if (!real_library) return;
    static const char *names[COUNT] = {{
{names}
    }};
    for (int i = 0; i < COUNT; i++) {{
        FARPROC found = GetProcAddress(real_library, names[i]);
        /* An export the real library lacks keeps a harmless stub, so an older or renamed
           library cannot take the game down at load time. */
        sdl3_targets[i] = found ? (target_t)(void (*)(void))found : (target_t)&missing_export;
    }}
}}

extern void hu_install_hooks(HINSTANCE self);

BOOL WINAPI DllMain(HINSTANCE self, DWORD reason, LPVOID reserved) {{
    (void)reserved;
    if (reason == DLL_PROCESS_ATTACH) {{
        DisableThreadLibraryCalls(self);
        load_real(self);
        hu_install_hooks(self);
    }}
    return TRUE;
}}
"""


def main() -> None:
    exports = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)

    stubs = HEADER
    for index, name in enumerate(exports):
        stubs += STUB.format(name=name, offset=index * 8)
    (out / "sdl3_stubs.S").write_text(stubs, encoding="utf-8")

    defblock = "; Generated by generate.py from the real SDL3 export table.\nEXPORTS\n"
    defblock += "".join(f"    {name}\n" for name in exports)
    (out / "sdl3_proxy.def").write_text(defblock, encoding="utf-8")

    names = "\n".join(f'        "{name}",' for name in exports)
    (out / "sdl3_proxy.c").write_text(
        C_SOURCE.format(count=len(exports), names=names), encoding="utf-8")
    print(f"{len(exports)} exports -> {out}")


if __name__ == "__main__":
    main()
